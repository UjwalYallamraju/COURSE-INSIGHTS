  // Large reports were triggering the browser's "Page Unresponsive" warning
  // because html2canvas does heavy synchronous rasterization work; running
  // many of those back-to-back with no gap blocks the main thread long enough
  // to trip Chrome's watchdog. Two things fix that: (1) yielding to the event
  // loop between every block via a 0ms timeout, which resets the watchdog and
  // lets the UI repaint, and (2) breaking big chunks like the password-not-set
  // list into one block per section instead of one giant block.
