// ---------- helpers ----------
function parseCell(raw) {
  if (raw === null || raw === undefined || raw === "") return { value: 0, notStarted: true };
  if (typeof raw === "number") return { value: raw, notStarted: raw <= 0 };
  const str = String(raw);
  const match = str.match(/-?\d+(\.\d+)?/);
  const num = match ? parseFloat(match[0]) : 0;
  const notStarted = /not started/i.test(str) || num <= 0;
  return { value: num, notStarted };
}

// Section identity always comes from the actual "Groups" column value on the
// row itself (groupStr) — this is what lets a single combined workbook with
// many sections mixed into one sheet split apart correctly, and what lets
// individual per-section files still work the same way. The filename is only
// ever a fallback for the rare row with a blank Groups cell.
function parseSectionMeta(groupStr, fileName) {
  const source = (groupStr && String(groupStr).trim()) || fileName;
  const m = String(source).match(/(\d{4}-\d{4})-([A-Za-z]+)-([A-Za-z0-9]+)/);
  if (m) {
    return {
      batch: m[1],
      branch: m[2].toUpperCase(),
      section: m[3].toUpperCase(),
      label: `${m[2].toUpperCase()}-${m[3].toUpperCase()}`,
    };
  }
  // No "batch-branch-section" pattern found — trust the raw Groups value
  // itself as the section identity rather than collapsing everything down
  // to the filename, which is what a combined multi-section sheet needs.
  return { batch: "—", branch: "General", section: source, label: source };
}

function shortCourseLabel(header) {
  let h = String(header).replace(/\s*\(%\)\s*$/i, "").trim();
  const parts = h.split(" - ");
  return parts[0].trim();
}

function courseCode(header) {
  let h = String(header).replace(/\s*\(%\)\s*$/i, "").trim();
  const parts = h.split(" - ");
  return parts.length > 1 ? parts[1].trim() : "";
}

function isFooterRow(row) {
  return row.some((c) => typeof c === "string" && /generated by/i.test(c));
}

async function parseWorkbook(file) {
  const buf = await file.arrayBuffer();
  const wb = XLSX.read(buf, { type: "array" });
  const ws = wb.Sheets[wb.SheetNames[0]];
  const rows = XLSX.utils.sheet_to_json(ws, { header: 1, defval: null, blankrows: false });
  if (!rows.length) throw new Error("Empty sheet");
  const header = rows[0].map((h) => (h === null ? "" : String(h).trim()));
  const body = rows.slice(1).filter((r) => r && r.length && !isFooterRow(r) && r[0] !== null && r[1] !== null);

  if (header.includes("Created Time")) {
    // password-not-set report: Name, Email, Groups, Created Time
    const nameIdx = header.indexOf("Name");
    const emailIdx = header.indexOf("Email");
    const groupIdx = header.indexOf("Groups");
    const timeIdx = header.indexOf("Created Time");
    const entries = body.map((r) => ({
      name: r[nameIdx] ?? "",
      email: r[emailIdx] ?? "",
      groups: r[groupIdx] ?? "",
      createdTime: timeIdx >= 0 ? r[timeIdx] ?? "" : "",
    }));
    // File-level meta is only an approximation (first row's Groups value) used
    // for the upload-list chip label. Real section grouping happens later,
    // per entry, off each entry's own `groups` value.
    const meta = parseSectionMeta(entries[0]?.groups, file.name);
    return { kind: "password", fileName: file.name, meta, entries };
  }

  if (header.includes("Member Id") || header.includes("Groups")) {
    // group-wise course progress report
    const idIdx = header.indexOf("Member Id");
    const nameIdx = header.indexOf("Name");
    const emailIdx = header.indexOf("Email");
    const groupIdx = header.indexOf("Groups");
    const courseIdxs = header
      .map((h, i) => ({ h, i }))
      .filter(({ h, i }) => i > groupIdx && h && h !== "");
    const courses = courseIdxs.map(({ h }) => ({
      key: h,
      label: shortCourseLabel(h),
      code: courseCode(h),
    }));

    const students = body.map((r) => {
      const courseValues = {};
      let sum = 0;
      courseIdxs.forEach(({ h, i }) => {
        const { value, notStarted } = parseCell(r[i]);
        courseValues[h] = { value, notStarted };
        sum += value;
      });
      const avg = courseIdxs.length ? sum / courseIdxs.length : 0;
      return {
        id: idIdx >= 0 ? r[idIdx] : "",
        name: nameIdx >= 0 ? r[nameIdx] : "",
        email: emailIdx >= 0 ? r[emailIdx] : "",
        groups: groupIdx >= 0 ? r[groupIdx] : "",
        courseValues,
        avg,
      };
    });

    // Same story as above: file-level meta is only a display approximation.
    const meta = parseSectionMeta(students[0]?.groups, file.name);
    return { kind: "course", fileName: file.name, meta, courses, students };
  }

  throw new Error("Unrecognized report format — expected a 'group-wise course' or 'password-not-set' export.");
}

function fmtPct(n) {
  return `${n.toFixed(1)}%`;
}

